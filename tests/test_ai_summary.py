import json
from types import SimpleNamespace
import pytest

from app.ai_summary import build_prompt, build_template_summary, generate_summary
from app.analysis import aggregate_by_category, compute_rows, compute_totals, detect_anomalies
from app.extensions import db
from app.models import CostItem, Project


def data():
    rows = compute_rows([dict(category="Materials", estimated=100, actual=150), dict(category="Labour", estimated=100, actual=90)])
    return compute_totals(rows), aggregate_by_category(rows), detect_anomalies(rows)


def test_template_numbers():
    text = build_template_summary(*data())
    assert "200.00" in text and "240.00" in text and "+40.00" in text and "+20.00%" in text
    assert "Materials" in text and "Labour" in text and "1 unusual" in text


def test_prompt_allowlist_and_limits():
    totals, categories, anomalies = data()
    categories = [{**categories[0], "category": str(i) + "x" * 100, "project_name": "PRIVATE_PROJECT", "username": "PRIVATE_USER"} for i in range(30)]
    prompt = build_prompt(totals, categories, anomalies)
    payload = json.loads(prompt.split("AGGREGATE DATA (JSON):\n")[1])
    assert len(payload["categories"]) == 20
    assert all(len(row["category"]) == 50 for row in payload["categories"])
    assert "PRIVATE_PROJECT" not in prompt and "PRIVATE_USER" not in prompt
    assert "untrusted data" in prompt
    assert "Variance = actual - estimated" in prompt


def test_anomaly_payload_uses_full_category_aggregate():
    rows = compute_rows([dict(category="A", estimated=10, actual=20), dict(category="A", estimated=10, actual=10)])
    prompt = build_prompt(compute_totals(rows), aggregate_by_category(rows), detect_anomalies(rows))
    payload = json.loads(prompt.split("AGGREGATE DATA (JSON):\n")[1])
    assert payload["flagged_categories"][0]["actual"] == 30
    assert "reason" not in payload["flagged_categories"][0]


