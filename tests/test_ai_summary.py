@pytest.mark.parametrize("result,source", [("Budget is stable. **Review** costs.", "gemini"), (RuntimeError("private request data"), "template"), ("", "template"), (None, "template"), ("x" * 2001, "template"), ("***", "template")])
def test_mocked_gemini_paths(app, owned_project, monkeypatch, caplog, result, source):
    captured = {}

    class FakeClient:
        def __init__(self, **kwargs):
            captured.update(kwargs)
            self.models = self

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

        def generate_content(self, **kwargs):
            captured.update(kwargs)
            if isinstance(result, Exception):
                raise result
            return SimpleNamespace(text=result)

    monkeypatch.setattr("app.ai_summary.genai.Client", FakeClient)
    app.config["GEMINI_API_KEY"] = "test-only-key"
    with app.app_context():
        text, actual_source = generate_summary(db.session.get(Project, owned_project.id))
    assert actual_source == source
    assert text and "*" not in text
    assert captured["http_options"].timeout == 15000
    assert captured["http_options"].retry_options.attempts == 1
    assert "Campus renovation" not in captured["contents"]
    assert "private request data" not in caplog.text and "test-only-key" not in caplog.text


def test_summary_route_and_invalidation(app, client, owned_project):
    assert b"at least one cost item" in client.post(f"/projects/{owned_project.id}/analysis", follow_redirects=True).data
    client.post(f"/projects/{owned_project.id}/items", data=dict(category="A", estimated=100, actual=120))
    response = client.post(f"/projects/{owned_project.id}/analysis", follow_redirects=True)
    assert b"Generated by built-in template" in response.data
    with app.app_context():
        project = db.session.get(Project, owned_project.id)
        assert project.ai_summary_at and project.ai_summary_source == "template"
        item_id = project.items[0].id
    client.post(f"/projects/{owned_project.id}/items/{item_id}/delete")
    with app.app_context():
        project = db.session.get(Project, owned_project.id)
        assert project.ai_summary is project.ai_summary_source is project.ai_summary_at is None
